create policy "public update group members" on public.group_members for update to anon, authenticated using (true) with check (true);

drop policy if exists "public read group messages" on public.group_messages;
create policy "public read group messages" on public.group_messages for select to anon, authenticated using (true);
drop policy if exists "public insert group messages" on public.group_messages;
create policy "public insert group messages" on public.group_messages for insert to anon, authenticated with check (true);

drop policy if exists "public read announcements" on public.group_announcements;
